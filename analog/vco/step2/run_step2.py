import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(HERE, "out")
os.environ.setdefault("PDK_ROOT", "/foss/pdks")
os.environ.setdefault("PDK", "ihp-sg13g2")
sys.path.append("/foss/tools/vacask/lib/vacask/python")
sys.path.insert(0, os.path.join(REPO, "analog", "pn-validation"))
sys.path.insert(0, os.path.join(REPO, "analog", "vco", "step1"))

VCT = 1.1            # VDD_VCO (D10)
ITAIL = 3.5e-3       # tail current for this first run
F_TARGET = 3.65e9    # band for the pnoise run (UHF 456 MHz x 8 / VHF 152 MHz x 24)
VTUNE_WIN = (0.3, 1.0)
VTUNE_MID = 0.65
OFFSETS = [3e4, 1e5, 3e5, 6e5, 1e6, 2e6, 1e7]
TARGET_1M = -116.0   # VHF target at 1 MHz (UHF -115), spec/phase2-plan.md 2.1
DUPLEX = {6e5: -108.4, 2e6: -117.9}   # allowed at the VCO at the VHF / UHF duplex offsets
V_OX = 1.5           # oxide limit with 10 % margin (step 1)

LSB_FF = 7.5         # differential on-capacitance of the LSB, fF (D8: 7 bits); resized by size()
C_FIX_FF = 0.0       # extra fixed differential capacitance, fF; set by size()
NFING = 20           # varactor fingers (two instances of nx = NFING / 2)
C_TOP_FF = 762.0     # wanted total at code 0 (4.37 GHz with L + 3 %, tank_budget.py)
C_SWITCH_FF = 955.0  # wanted switched range (down to 3.00 GHz with L - 3 %)
R_CELL = 3.4         # C_on / C_off of the bank cell (step 1, about 100 um per 60 fF)
A_TARGET = 1.3       # wanted differential amplitude, V (1.5 V limit with margin)
R_BIAS = 2e6         # bank and varactor bias resistors, ohm. First pnoise run: at 200 kOhm the varactor bias
                     # (rvp/rvn, 21 %) and the off MSB bias (rba6/rbb6, 15 %) were 36 % of the noise at 1 MHz
C_TB = 2e-12         # buffer common node to ground: the buffer pair was 26 % at 1 MHz with an ideal tail
SW_PER_FF = 100 / 60  # um of switch per fF (step 1)
CAP_AREA = 1.5       # fF/um^2 (cap_rfcmim, process spec)

HEADER = """{title}

include "sg13g2_vacask_common.lib"
include "cornerMOSlv.lib" section=mos_tt
include "cornerMOShv.lib" section=mos_tt
include "cornerCAP.lib" section=cap_typ

load "resistor.osdi"
load "capacitor.osdi"
load "inductor.osdi"

model resistor  resistor
model capacitor capacitor
model inductor  inductor
model vsource   vsource
model isource   isource
"""


def noisy_inductor():
    src = os.path.join(REPO, "analog", "vco", "models", "l2n0_lumped.inc")
    if not os.path.exists(src):
        sys.exit("analog/vco/models/l2n0_lumped.inc missing: run analog/vco/step1/run_step1.py ind first")
    text = open(src).read()
    text = re.sub(r"(resistor r=[^\s]+)", r"\1 noisy=1", text)
    dst = os.path.join(OUT, "l2n0_lumped_noisy.inc")
    open(dst, "w").write("// noisy copy of analog/vco/models/l2n0_lumped.inc (generated by run_step2.py)\n" + text)
    return dst


def svaricap():
    import run_step1
    run_step1.OUT = OUT
    return run_step1.svaricap_fixed()


def side(c_ff):
    """Square cap_rfcmim side (um) for capacitance c_ff (fF), ignoring the fringe."""
    return math.sqrt(c_ff / CAP_AREA)


def netlist(title, code, vtune, analysis, itail=ITAIL, extra=""):
    ind, var = noisy_inductor(), svaricap()
    n = []
    n.append(f'include "{ind}"\ninclude "{var}"\n')
    n.append(f"vdd  (vdd 0) vsource dc=1.2\nvct  (ct 0)  vsource dc={VCT}\n")
    n.append("xl (tp tn ct) l2n0\n")
    if C_FIX_FF > 0:
        sf = side(2 * C_FIX_FF)                          # two MIMs in series, bottom plates to a mid node
        n.append(f"xf1 (tp fx 0) cap_rfcmim w={sf:.3f}u l={sf:.3f}u\n"
                 f"xf2 (tn fx 0) cap_rfcmim w={sf:.3f}u l={sf:.3f}u\n"
                 "rfx (fx 0) resistor r=200k noisy=1\n")
    n.append("m1 (tp tn tail 0) sg13_lv_nmos w=32u l=0.13u ng=8\n"
             "m2 (tn tp tail 0) sg13_lv_nmos w=32u l=0.13u ng=8\n")
    n.append("ctail (tail 0) capacitor c=8p\n"
             "mt (tail nbf 0 0) sg13_lv_nmos w=160u l=4u ng=32\n"
             "rbf (nb nbf) resistor r=1M noisy=1\n"
             "cbf (nbf 0) capacitor c=50p\n"
             "mr (nb nb 0 0) sg13_lv_nmos w=20u l=4u ng=4\n"
             f"iref (vdd nb) isource dc={itail / 8:.6g}\n")
    for k in range(7):
        c_mim = 2 * LSB_FF * 2 ** k                      # each MIM is twice the differential value
        s = side(c_mim)
        w = SW_PER_FF * LSB_FF * 2 ** k
        ng = max(1, int(round(w / 2.5)))
        on = (code >> k) & 1
        n.append(f"xb{k}p (tp a{k} 0) cap_rfcmim w={s:.3f}u l={s:.3f}u\n"
                 f"xb{k}n (tn b{k} 0) cap_rfcmim w={s:.3f}u l={s:.3f}u\n"
                 f"ms{k} (a{k} g{k} b{k} 0) sg13_lv_nmos w={w:.2f}u l=0.13u ng={ng}\n"
                 f"rba{k} (a{k} bb{k}) resistor r={R_BIAS:g} noisy=1\n"
                 f"rbb{k} (b{k} bb{k}) resistor r={R_BIAS:g} noisy=1\n"
                 f"vg{k} (g{k} 0) vsource dc={1.2 if on else 0}\n"
                 f"vbb{k} (bb{k} 0) vsource dc={0 if on else 1.2}\n")
    # varactor: NFING fingers, per side about NFING x 3.4 x 2 fF; coupling caps 5x per side
    sc = side(5 * NFING * 6.8)
    n.append(f"xcp (tp vgp 0) cap_rfcmim w={sc:.3f}u l={sc:.3f}u\n"
             f"xcn (tn vgn 0) cap_rfcmim w={sc:.3f}u l={sc:.3f}u\n"
             f"rvp (vgp vvb) resistor r={R_BIAS:g} noisy=1\n"
             f"rvn (vgn vvb) resistor r={R_BIAS:g} noisy=1\n"
             "vvb (vvb 0) vsource dc=0.3\n"
             f"xv1 (vgp vt vgn 0) sg13_hv_svaricap_fx w=3.74u l=0.3u nx={NFING - NFING // 2}\n"
             f"xv2 (vgp vt vgn 0) sg13_hv_svaricap_fx w=3.74u l=0.3u nx={NFING // 2}\n"
             f"vtune (vt 0) vsource dc={vtune}\n")
    n.append("mb1 (op tp tb 0) sg13_lv_nmos w=10u l=0.13u ng=4\n"
             "mb2 (on tn tb 0) sg13_lv_nmos w=10u l=0.13u ng=4\n"
             "rl1 (vdd op) resistor r=400 noisy=1\nrl2 (vdd on) resistor r=400 noisy=1\n"
             "ib (tb 0) isource dc=1m\n"
             f"ctb (tb 0) capacitor c={C_TB:g}\n"
             "cl1 (op 0) capacitor c=20f\ncl2 (on 0) capacitor c=20f\n")
    n.append('ik (0 tn) isource type="pulse" val0=0 val1=1m delay=1n rise=50p fall=50p width=200p\n')
    n.append(extra)
    body = "".join(n)
    path = os.path.join(OUT, title + ".sim")
    with open(path, "w") as fh:
        fh.write(HEADER.format(title=f"P2.3 step 2 VCO: {title}") + body +
                 "\ncontrol\n  abort always\n  options rawfile=\"binary\"\n" + analysis + "\nendc\n")
    return path


def run(sim):
    name = os.path.basename(sim)[:-4]
    log = os.path.join(OUT, name + ".log")
    with open(log, "w") as fh:
        r = subprocess.run(["vacask", name + ".sim"], cwd=OUT, stdout=fh, stderr=subprocess.STDOUT)
    if r.returncode:
        raise RuntimeError(f"vacask {name}.sim failed (exit {r.returncode}); end of out/{name}.log:\n"
                           + open(log).read()[-1500:])


def measure(raw):
    """Frequency, differential amplitude and peak device voltages over the last 20 ns."""
    from vacask.rawfile import rawread
    d = rawread(raw).get()
    t = np.real(d["time"])
    vp, vn, vt = np.real(d["tp"]), np.real(d["tn"]), np.real(d["tail"])
    m = t >= t[-1] - 20e-9
    t, vp, vn, vt = t[m], vp[m], vn[m], vt[m]
    v = vp - vn
    s = np.sign(v)
    idx = np.where((s[:-1] < 0) & (s[1:] >= 0))[0]
    tz = t[idx] - v[idx] * (t[idx + 1] - t[idx]) / (v[idx + 1] - v[idx])
    if len(tz) < 3:
        return None
    f = (len(tz) - 1) / (tz[-1] - tz[0])
    amp = (v.max() - v.min()) / 2
    vgs = max((vp - vt).max(), (vn - vt).max())
    vgd = max(v.max(), (-v).max())
    return dict(f=f, amp=amp, vgs=vgs, vgd=vgd, vtail_min=vt.min(), vdrain_min=min(vp.min(), vn.min()))


def tran(code, vtune, tag, itail=ITAIL):
    sim = netlist(f"vco_tr_{tag}", code, vtune, itail=itail, analysis=
                  "  save v(tp) v(tn) v(tail)\n  analysis tr tran stop=60n step=5p maxstep=5p")
    run(sim)
    return measure(os.path.join(OUT, "tr.raw"))


def c_of(f):
    """Total differential tank capacitance (fF) at frequency f with the model's L near that frequency."""
    return 1e15 / ((2 * math.pi * f) ** 2 * 1.70e-9)


def size():
    """Scale the bank and add fixed capacitance so code 0 / 127 land at C_TOP / C_TOP + C_SWITCH (two passes).

    First run (2026-10-20): with LSB 7.5 fF of ON capacitance the bank switched only about 644 fF (the
    off-state capacitance subtracts) and the fixed capacitance was about 420 fF instead of the budgeted 762,
    so the VCO ran at 3.75-5.96 GHz.
    """
    global LSB_FF, C_FIX_FF
    print("## Sizing (bank scale and fixed capacitor, two passes)\n")
    for it in range(2):
        m0, m1 = tran(0, VTUNE_MID, f"size{it}_c0"), tran(127, VTUNE_MID, f"size{it}_c127")
        c0, c1 = c_of(m0["f"]), c_of(m1["f"])
        dc = c1 - c0
        scale = C_SWITCH_FF / dc
        coff = dc / (R_CELL - 1)                       # bank off-state capacitance inside c0
        c0_new = c0 + (scale - 1) * coff
        fix = C_FIX_FF + (C_TOP_FF - c0_new)
        print(f"pass {it+1}: LSB {LSB_FF:.2f} fF, fixed {C_FIX_FF:.0f} fF -> code 0 {m0['f']/1e9:.3f} GHz "
              f"({c0:.0f} fF), code 127 {m1['f']/1e9:.3f} GHz ({c1:.0f} fF), switched {dc:.0f} fF")
        LSB_FF *= scale
        C_FIX_FF = max(0.0, fix)
        if fix < 0:
            print(f"  fixed capacitance already {-fix:.0f} fF above the 762 fF target: the top edge cannot be reached")
    print(f"result: LSB {LSB_FF:.2f} fF (on-state), fixed {C_FIX_FF:.0f} fF differential, varactor {NFING} fingers\n")


def do_range():
    size()
    print("## Tuning range and swing (noiseless transient, 60 ns, last 20 ns measured)\n")
    print(f"I_tail {ITAIL*1e3:.1f} mA, VDD_VCO {VCT} V. Peak V_GS / V_GD of the core against {V_OX} V.\n")
    print("| Code | V_tune | f (GHz) | Diff. amplitude (V) | Peak V_GS | Peak V_GD | Tail min | Drain min |")
    print("|---|---|---|---|---|---|---|---|")
    res = {}
    pts = [(c, v) for c in (0, 32, 64, 96, 127) for v in (VTUNE_WIN[0], VTUNE_MID, VTUNE_WIN[1])]
    for code, vt in pts:
        try:
            m = tran(code, vt, f"c{code}_v{vt}")
        except RuntimeError as e:
            print(f"| {code} | {vt} | failed: {str(e).splitlines()[0]} |")
            continue
        if not m:
            print(f"| {code} | {vt} | no oscillation |")
            continue
        res[f"{code},{vt}"] = m
        flag = lambda x: f"**{x:.2f}**" if x > V_OX else f"{x:.2f}"          # noqa: E731
        print(f"| {code} | {vt:.2f} | {m['f']/1e9:.4f} | {m['amp']:.3f} | {flag(m['vgs'])} | {flag(m['vgd'])} | "
              f"{m['vtail_min']:.2f} | {m['vdrain_min']:.2f} |")
    print()
    def f(c, v):
        m = res.get(f"{c},{v}")
        return m["f"] if m else float("nan")
    lo, hi = f(127, VTUNE_WIN[1]), f(0, VTUNE_WIN[0])
    print(f"Range: {lo/1e9:.3f}-{hi/1e9:.3f} GHz (needed 3.12-4.20, design 3.00-4.37 GHz): "
          f"{'covers' if lo <= 3.12e9 and hi >= 4.20e9 else 'DOES NOT cover'} the band.")
    for c in (0, 64, 127):
        k = (f(c, VTUNE_WIN[1]) - f(c, VTUNE_WIN[0])) / (VTUNE_WIN[1] - VTUNE_WIN[0])
        print(f"KVCO at code {c}: {abs(k)/1e6:.1f} MHz/V (needed about 14-47 MHz/V over the range, D8)")
    # code for the pnoise band: C is linear in code, so 1/f^2 is linear in code
    codes = [c for c in (0, 32, 64, 96, 127) if f(c, VTUNE_MID) == f(c, VTUNE_MID)]
    y = [1 / f(c, VTUNE_MID) ** 2 for c in codes]
    if len(codes) >= 2:
        a, b = np.polyfit(codes, y, 1)
        code = int(round(min(127, max(0, (1 / F_TARGET ** 2 - b) / a))))
        m = tran(code, VTUNE_MID, f"c{code}_pick")
        print(f"\nBand for pnoise: code {code} at V_tune {VTUNE_MID} V -> {m['f']/1e9:.4f} GHz (target {F_TARGET/1e9} GHz)")
        itail = min(5e-3, ITAIL * A_TARGET / m["amp"])
        m2 = tran(code, VTUNE_MID, f"c{code}_pick_i", itail=itail)
        print(f"Tail current for {A_TARGET} V: {itail*1e3:.2f} mA -> {m2['amp']:.3f} V, {m2['f']/1e9:.4f} GHz, "
              f"peak V_GS {m2['vgs']:.2f} / V_GD {m2['vgd']:.2f} V")
        print("\nTail current per band for about 1.3 V (VCO_BIAS): " + ", ".join(
            f"code {c}: {min(5e-3, ITAIL * A_TARGET / res[f'{c},{VTUNE_MID}']['amp'])*1e3:.1f} mA"
            for c in (0, 32, 64, 96, 127) if f"{c},{VTUNE_MID}" in res))
        json.dump(dict(code=code, vtune=VTUNE_MID, f=m2["f"], itail=itail, lsb=LSB_FF, cfix=C_FIX_FF,
                       nfing=NFING, meas=res), open(os.path.join(OUT, "range.json"), "w"), indent=1)


def do_pn():
    from vacask.rawfile import rawread
    from compare import fundamental_amplitude
    rj = os.path.join(OUT, "range.json")
    if not os.path.exists(rj):
        sys.exit("out/range.json missing: run 'python3 run_step2.py range' first")
    global LSB_FF, C_FIX_FF, NFING
    r = json.load(open(rj))
    code, vt, f0 = r["code"], r["vtune"], r["f"]
    LSB_FF, C_FIX_FF, NFING, itail = r.get("lsb", LSB_FF), r.get("cfix", C_FIX_FF), r.get("nfing", NFING), \
        r.get("itail", ITAIL)
    vals = ", ".join(f"{x:.0f}" for x in OFFSETS)
    print(f"\n## Phase noise, code {code}, V_tune {vt} V, I_tail {itail*1e3:.2f} mA (pss/pnoise, pss_minpts 16000)\n")
    # Runs 1-2: the PSS stabilisation transient failed (NR, timestep too small) at reltol 1e-7 and 1e-6,
    # although plain transients of the same circuit run. So the limit cycle is now reached with a plain
    # transient (stored as "ss") and the shooting starts from it without a stabilisation transient.
    # Runs 3-4: reltol 1e-7 did not converge in 50 shooting iterations (about 14 min); 1e-6 converged.
    # Try 1e-6 first (its accuracy is checked on the validated level 2 in step 3).
    attempts = (("reltol=1e-6 pss_tolscale=1e-3", 16000), ("reltol=1e-7 pss_tolscale=1e-4", 16000),
                ("reltol=1e-6 pss_tolscale=1e-3", 8000))
    for opts, npts in attempts:
        sim = netlist("vco_pn", code, vt, itail=itail, analysis=
                      f"  options {opts} pss_minpts={npts}\n"
                      '  analysis warm tran stop=60n step=5p maxstep=5p store="ss"\n'
                      "  save full\n"
                      f'  analysis pn pnoise oscillator=1 tper={1/f0:.6e} tstab=0 ic="ss" icmode="uic" '
                      f'maxharm=32 truncharm=16 in="iin" out=["tp", "tn"] outharm=1 values=[{vals}] writepss=1',
                      extra="iin (0 tp) isource dc=0\n")
        try:
            run(sim)
            print(f"pss converged with {opts}, pss_minpts {npts}"
                  + (" (offsets below about 60 kHz less accurate)" if npts < 16000 else ""))
            break
        except RuntimeError as e:
            tail = [x for x in str(e).splitlines() if x.strip()][-4:]
            print(f"pss failed with {opts}, pss_minpts {npts}: " + " | ".join(tail))
    else:
        sys.exit("pss/pnoise failed with all settings; see out/vco_pn.log")
    pss = rawread(os.path.join(OUT, "pn.pss.raw")).get()
    a, fp = fundamental_amplitude(pss["time"], np.real(pss["tp"]) - np.real(pss["tn"]))
    pn = rawread(os.path.join(OUT, "pn.raw")).get()
    off = np.real(pn["frequency"])
    l = 10 * np.log10(np.real(pn["onoise"]) / (a * a / 2))
    print(f"f0 {fp/1e9:.4f} GHz, differential amplitude {a:.3f} V\n")
    print("| Offset | L (dBc/Hz) | Limit at the VCO | Margin |")
    print("|---|---|---|---|")
    for d, li in zip(off, l):
        lim = TARGET_1M if abs(d - 1e6) < 1 else DUPLEX.get(round(d))
        lim_s = f"{lim:.1f}" if lim is not None else "—"
        mar = f"{lim - li:+.1f} dB" if lim is not None else "—"
        print(f"| {d/1e3:.0f} kHz | {li:.1f} | {lim_s} | {mar} |")
    # flicker corner from the slope between neighbouring offsets
    print("\nSlope (dB/decade) between offsets: " + ", ".join(
        f"{off[i]/1e3:.0f}-{off[i+1]/1e3:.0f} kHz {((l[i+1]-l[i])/math.log10(off[i+1]/off[i])):.1f}"
        for i in range(len(off) - 1)))
    print("(-20 = thermal, -30 = flicker region)")


def do_contrib():
    """Noise contributions from out/pn.raw (no new simulation): share of each instance at a few offsets."""
    from vacask.rawfile import rawread
    pn = rawread(os.path.join(OUT, "pn.raw")).get()
    allnames = [x.decode() if isinstance(x, bytes) else x for x in getattr(pn, "names", [])]
    names = [k for k in allnames if k.startswith("n(") and "," not in k]
    if not names:
        print("out/pn.raw has no per-instance contributions (n(instance)); rerun 'pn' with 'save full'")
        return
    off = np.real(pn["frequency"])
    tot = np.real(pn["onoise"])
    groups = {}
    for k in names:
        inst = k[2:-1]
        groups.setdefault(inst, np.zeros_like(tot))
        groups[inst] = groups[inst] + np.abs(np.real(pn[allnames.index(k)]))
    show = [6e5, 1e6, 2e6]
    cols = [int(np.argmin(np.abs(off - x))) for x in show]
    print("\n## Noise contributions (share of the output noise)\n")
    print("| Instance | " + " | ".join(f"{off[c]/1e3:.0f} kHz" for c in cols) + " |")
    print("|---|" + "---|" * len(cols))
    rank = sorted(groups, key=lambda g: -groups[g][cols[1]])
    for g in rank[:15]:
        print(f"| {g} | " + " | ".join(f"{100*groups[g][c]/tot[c]:.1f} %" for c in cols) + " |")
    print("\nSum of all instances / onoise at 1 MHz: "
          f"{100*sum(groups[g][cols[1]] for g in groups)/tot[cols[1]]:.0f} % (100 % expected)")


def main():
    os.makedirs(OUT, exist_ok=True)
    what = sys.argv[1:] or ["range", "pn"]
    if "range" in what:
        do_range()
    if "pn" in what:
        do_pn()
    if "pn" in what or "contrib" in what:
        do_contrib()


if __name__ == "__main__":
    main()
